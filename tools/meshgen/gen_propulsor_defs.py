def blur_material(root):
    """The blur disc's material (BLUR_MAT): two source PNGs (albedo, alpha), the three packed textures as Keen's materials
    have them (.comptex on the engine's PBRMaterialTemplate presets: colour + metal + alpha, normal + roughness - all
    defaults -, ambient occlusion + emissive + colour mask + alpha) and the PBRTransparent material definition.
    The texture is the disc seen from above: radius 1 at its edge, the blade tips at BLUR_TIP_RHO (rotor_split.py maps the
    disc's UVs so), the hinge at R0 / R1 of that."""
    import numpy as np
    from PIL import Image
    rel = os.path.join(ROOT_REL, "Materials", BLUR_MAT); d = os.path.join(gd.BLOCKS, "Assets", rel)
    os.makedirs(d, exist_ok=True)
    W = 1024
    y, x = np.mgrid[0:W, 0:W].astype(np.float64)
    rho = np.hypot((x + 0.5) / W * 2 - 1, (y + 0.5) / W * 2 - 1)
    tip = BLUR_TIP_RHO; hinge = tip * 0.45 / 4.45; band = tip * (0.45 + 0.90 * 4.0) / 4.45   # (rotor_split.py R0, R1, TIP_BAND)
    ss = lambda a, b, v: np.clip((v - a) / (b - a), 0, 1) ** 2 * (3 - 2 * np.clip((v - a) / (b - a), 0, 1))
    # the blades sweep a share of each circle ~ chord x 3 / circumference: dense at the root, thin at the tips (kept
    # visible: a blur disc that vanishes at the tips reads as a small rotor)
    a = 0.19 + 0.28 * np.clip(0.16 / np.maximum(rho, 1e-3), 0, 1) ** 0.8
    a *= 1 + 0.09 * np.sin(2 * np.pi * rho * 23) + 0.05 * np.sin(2 * np.pi * rho * 61)   # (the twist and the paint: a faint grain)
    a = np.where(rho >= band, 0.42 + 0.05 * np.sin(2 * np.pi * (rho - band) / (tip - band) * 2.5), a)   # (the tip stripes' band)
    a *= ss(hinge, hinge + 0.03, rho) * (1 - ss(tip - 0.012, tip, rho))
    col = np.empty((W, W, 3)); dark = np.array([33.0, 34.0, 37.0]); yellow = np.array([168.0, 128.0, 30.0])
    t = ss(band - 0.004, band + 0.004, rho)[..., None]
    stripe = (0.5 + 0.5 * np.sin(2 * np.pi * (rho - band) / (tip - band) * 2.5))[..., None]   # (yellow / dark rings: the stripes, blurred)
    col[:] = dark * (1 + 0.15 * ss(0.3, tip, rho))[..., None]
    col = col * (1 - t) + t * (yellow * (0.55 + 0.45 * stripe) + dark * 0.45 * (1 - stripe))
    srcs = {}
    for nm, img in (("albedo", Image.fromarray(np.clip(col, 0, 255).astype(np.uint8), "RGB")),
                    ("alphamask", Image.fromarray(np.clip(a * 255, 0, 255).astype(np.uint8), "L")),
                    ("normal", Image.new("RGB", (256, 256), (128, 128, 255))), ("roughness", Image.new("L", (256, 256), 230))):
        f = f"{BLUR_MAT}_{nm}.png"; img.save(os.path.join(d, f))
        srcs[nm] = file_id(os.path.join(rel, f)); gd.write(os.path.join(d, f) + ".meta", gd.file_meta(srcs[nm]))
    ST = "VRage:Keen.VRage.ContentPipeline.Textures.Composite.CompositeTexturePresetModel+SourceTexture"
    packs = {"cm": ("b8c12ad6-a10b-4fdb-bbc0-8f2d655380f0", ["albedo", "albedo", "albedo", None, "alphamask"]),   # (PBRMaterialTemplate_ColorMetalTexture)
             "nr": ("91156de7-286c-4574-8b47-7ef12981f5a6", ["normal", "normal", "normal", "roughness"]),        # (..._NormalRoughnessTexture: flat, rough)
             "add": ("aa524acf-9017-43ff-a5d8-48fcbc48cade", [None, None, None, "alphamask"])}                   # (..._ExtensionsTexture)
    tex = {}
    for k, (preset, chans) in packs.items():
        f = f"{BLUR_MAT}_{k}.comptex"; tex[k] = file_id(os.path.join(rel, f))
        gd.write(os.path.join(d, f), {"$Bundles": {"System.Runtime": "1.0.0.0", "VRage": "2.3.0.2070"},
            "$Type": "VRage:Keen.VRage.ContentPipeline.Textures.Composite.CompositeTextureModel",
            "$Value": {"PresetReference": "{G}" + preset, "Rotation": "None", "Flip": "None",
                       "PresetModel": {"TextureSourceModels": [{"$Type": ST, "Texture": ("{G}" + srcs[c]) if c else None} for c in chans]}}})
        gd.write(os.path.join(d, f) + ".meta", gd.asset_meta(tex[k], ("P_TEXTURE", 5), f"{BLUR_MAT}_{k}.dds"))
    gd.definition(os.path.join(d, f"{BLUR_MAT}.def"), {"$Bundles": {"System.Runtime": "1.0.0.0", "VRage": "2.3.0.2070"},
        "$Type": "VRage:Keen.VRage.Core.Render.Materials.Templates.PBRTransparentMaterialDefinitionObjectBuilder",
        "$Value": {"Guid": BLUR_MAT_GUID, "DefaultState": "84886702-d56d-4404-a343-7fc98c238db8",   # (PBRTransparent, back faces culled: the disc has both)
                   "PinTextures": False, "CustomTexelDensity": None,
                   "ColorMetalTexture": "{G}" + tex["cm"], "NormalRoughnessTexture": "{G}" + tex["nr"], "ExtensionsTexture": "{G}" + tex["add"],
                   "EmissivityMultiplier": 0, "SpecularBaseColor": {"PackedValue": 0}, "FresnelTightness": 1}}, BLUR_MAT_GUID, False)


