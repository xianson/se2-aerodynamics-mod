def ex_load(rel):
    with open(os.path.join(VANILLA_PARTICLES, rel), encoding="utf-8-sig") as f: return json.load(f)


def ex_line(points):
    """A timeline over the EFFECT time (keys 0..1, fractions of its duration): [(t, value)] - a value may be an over-life curve."""
    return {"KeyFrames": {"_data": [{"Key": ex_kid(), "Value": {"Value": v, "Key": t}} for t, v in points]}}


def ex_life(points):
    """An over-LIFE curve (keys 0..1 of a particle's life; the game allows 1-4 keys)."""
    assert 1 <= len(points) <= 4, "the game allows 1-4 over-life keys"
    return {"KeyFrames": {"_data": [{"Key": ex_kid(), "Value": {"Value": v, "Key": t}} for t, v in points]}}


def ex_const(v): return ex_line([(0, v)])
def v3(x, y, z): return {"X": x, "Y": y, "Z": z}
def c4(r, g, b, a): return {"X": r, "Y": g, "Z": b, "W": a}


def ex_emitter(name, rel, guid, *, pps, life, velocity, cone, size, color, emissivity, scatter=None, local=False, inherit=1.0,
               emitter=(0, 0, 0), offset=(0, 0, 0), velocity_var=0.0, collide=False, extra=None):
    """One emitter: a copy of the vanilla emitter 'rel' (its texture, animation, billboard and rendering kept) with these timelines.
    pps / life: [(effect time, value)]; size / color / emissivity / scatter: (effect time -> over-life points) lists."""
    d = ex_load(rel); v = d["$Value"]; v["Guid"] = guid
    t = v["TimeLines"]
    t["ParticlesPerSecond"] = ex_line(pps)
    t["ParticleLifeSpan"] = ex_line(life)
    t["LinearVelocity"] = ex_const(velocity)              # (constant over the effect time: the plume's length is the code's)
    t["LinearVelocityVariance"] = ex_const(velocity_var)
    t["ConeAngle"] = ex_const(cone)
    t["ConeInnerAngle"] = ex_const(0)
    t["EmitterSize"] = ex_const(v3(*emitter))
    t["EmitterShellThickness"] = ex_const(1)
    t["Offset"] = ex_const(v3(*offset))
    t["AccelerationFactor"] = ex_const(ex_life([(0, 0), (1, 0)]))
    t["ParticleSize"] = ex_line([(k, ex_life(p)) for k, p in size])
    t["Color"] = ex_line([(k, ex_life(p)) for k, p in color])
    t["Emissivity"] = ex_line([(k, ex_life(p)) for k, p in emissivity])
    if scatter is not None: t["ScatteringIntensity"] = ex_line([(k, ex_life(p)) for k, p in scatter])
    v["EmitterFlags"].update({"EnableCollisions": collide, "EnableLocalSpaceSimulation": local})
    v["SimulationParameters"].update({"EmitterMotionInheritance": inherit})
    v["EmissionParameters"].update({"ParticleBurst": 0, "Direction": v3(0, 0, 1)})
    # (SE2 4.0: the hydrogen flames are parameter-driven; ours are not - spawned through TrySpawnEffect, their time held by
    #  EffectTime (the same render call the parameter makes) - and effect and emitters must agree, so the flag is cleared)
    if "IsParameterDriven" in v["EmissionParameters"]: v["EmissionParameters"]["IsParameterDriven"] = False
    v["RenderingParameters"].update({"DistanceScalingFactor": 0})
    for k, x in (extra or {}).items(): v[k].update(x)
    out = os.path.join(gd.BLOCKS, "Assets", EXHAUST_REL, f"AeroExhaust_{name}_ParticleEmitter.def")
    gd.definition(out, d, guid, False)
    return guid


