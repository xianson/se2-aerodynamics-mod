# the side ports' centre along the block (VRage z, block space before the +0.125 offset, +Z aft) - the user's placement
# (2026-10-17: moved; an explicit table, never the mount slab's middle, never clamped to it)
RAMJET_PORT_Z = {"Ramjet_050": 0.25, "Ramjet_150": 1.00, "Ramjet_250": 1.25, "Ramjet_750": 3.75}


def ramjet_ports(s):
    """The ramjet's conveyor ports (the vanilla hydrogen thrusters' ConveyorLeft01 / Right dummies, their type and turns): two, on
    the +X / -X side faces just inside the face (x = +-half width, y 0), centred at RAMJET_PORT_Z along the block. 0.5 m ports
    on the 0.5 / 1.5 m blocks (as the 1.5 m HydrogenThruster200's sides), 1.5 m ports on the 2.5 m / 7.5 m (as the
    HydrogenThruster750's). A port outside the exported side mount slab is generated as placed, with a warning."""
    mf = s["mount_faces_vrage"]
    zs = [v[2] for box in mf.values() for v in box]
    zlo, zhi = min(zs), max(zs)
    port = 0.5 if s["size"] in ("050", "150") else 1.5
    zc = RAMJET_PORT_Z[s["name"]]
    if zc - port / 2 < zlo - 1e-6 or zc + port / 2 > zhi + 1e-6:
        print(f"WARNING {s['name']}: its {port} m conveyor ports at z {zc} (z {zc - port / 2} .. {zc + port / 2}) are outside its side mount slab"
              f" (z {zlo} .. {zhi}) - generated as placed")
    hw = max(abs(v) for v in (s["box_lo"][0], s["box_hi"][0])) - 0.005
    r2 = 0.7071068
    out = []
    # (two ports only, the sides - the user, 2026-10-17: modelled flush in a cutout at these spots; no top / bottom ports)
    for name, pos, rot in (("ConveyorRight01", (hw, 0.0, zc), (0, -r2, 0, r2)), ("ConveyorLeft01", (-hw, 0.0, zc), (0, r2, 0, r2))):
        out.append(gd.dummy(name, P(pos), DT_CONVEYOR, rot, (port, port, 0.05)))
    return out, port, zc


def gen_ramjet(N, s, rows):
    """A RAMJET (2026-10-17): the vanilla HydrogenThruster250's chain (H) with our model (Ramjet_<N> - the modeller's kitbash of the
    vanilla atmospheric thruster it was built from), one TRANSLATING subpart - the inlet spike (Subpart01/<N>_S1_Spike, its origin
    on the axis at the spike's base, dummy "RamjetSpike" at the spec's subpart point, its own dummy type; no spin, entity
    "RamjetSpike"; the mod's AeroRamjetSpikeComponent slides it aft with the Mach) -, conveyor ports on the four mount faces, our
    numbers (thrust, hydrogen per second at full: ramjet_fuel), a near-zero flame (no particle effect: the exhaust is the mod's - gen_exhaust,
    Fx/AeroExhaustComponent), our placement and kind."""
    prefix = next(k for k in KINDS if N.startswith(k))
