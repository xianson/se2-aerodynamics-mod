"""meshio - OBJ / STL (ASCII + binary) reading and writing, and inside-testing a triangle soup on a grid.

Inside test: rays along each of the three axes through every sample line; the signed crossings give a winding
number (union of overlapping closed shells works), and the three axes vote (2 of 3) so near-closed meshes with
small holes still voxelise.
"""
from __future__ import annotations

import struct

import numpy as np


def read_obj(path):
    verts, faces = [], []
    with open(path, encoding="utf-8", errors="replace") as fh:
        lines = fh.readlines()
    for raw in lines:
        t = raw.split()
        if not t:
            continue
        if t[0] == "v":
            verts.append([float(v) for v in t[1:4]])
        elif t[0] == "f":
            idx = []
            for w in t[1:]:
                i = int(w.split("/")[0])
                idx.append(i - 1 if i > 0 else len(verts) + i)
            for k in range(1, len(idx) - 1):         # fan-triangulate polygons
                faces.append((idx[0], idx[k], idx[k + 1]))
    v = np.array(verts, float)
    return v[np.array(faces, int)]


def read_stl(path):
    with open(path, "rb") as fh:
        data = fh.read()
    if len(data) >= 84:
        n = struct.unpack("<I", data[80:84])[0]
        if 84 + 50 * n == len(data):
            rec = np.frombuffer(data[84:], dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]),
                                count=n)
            return rec["v"].astype(float)
    tris, cur = [], []
    for line in data.decode("utf-8", errors="replace").splitlines():
        t = line.split()
        if t and t[0] == "vertex":
            cur.append([float(x) for x in t[1:4]])
            if len(cur) == 3:
                tris.append(cur)
                cur = []
    return np.array(tris, float)


def read_mesh(path):
    return read_stl(path) if path.lower().endswith(".stl") else read_obj(path)


def write_obj(path, tris, groups=None):
    """Triangles (n, 3, 3) as an OBJ; groups: optional list of (name, start, count) for 'o' lines."""
    with open(path, "w", encoding="utf-8") as f:
        f.write("# generated by gridgen\n")
        for k, tri in enumerate(tris):
            for v in tri:
                f.write(f"v {v[0]:.5f} {v[1]:.5f} {v[2]:.5f}\n")
        g = {s: name for name, s, c in (groups or [])}
        for k in range(len(tris)):
            if k in g:
                f.write(f"o {g[k]}\n")
            f.write(f"f {3 * k + 1} {3 * k + 2} {3 * k + 3}\n")


def write_stl(path, tris):
    tris = np.asarray(tris, np.float32)
    n = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    n /= np.maximum(np.linalg.norm(n, axis=1, keepdims=True), 1e-12)
    with open(path, "wb") as f:
        f.write(b"gridgen binary stl".ljust(80, b" "))
        f.write(struct.pack("<I", len(tris)))
        for i in range(len(tris)):
            f.write(struct.pack("<3f", *n[i]))
            f.write(tris[i].astype("<f4").tobytes())
            f.write(b"\0\0")


AXES = {"x": 0, "y": 1, "z": 2}


def map_axes(tris, spec: str):
    """spec: three tokens giving the file axis for design x (aft), y (right), z (up), e.g. "x y z" or "-z x y"."""
    toks = spec.split()
    out = np.empty_like(tris)
    for k, tok in enumerate(toks):
        sgn = -1.0 if tok.startswith("-") else 1.0
        out[..., k] = sgn * tris[..., AXES[tok.lstrip("+-")]]
    if np.linalg.det(np.array([[(-1 if t.startswith("-") else 1) * (AXES[t.lstrip("+-")] == j) for j in range(3)]
                               for t in toks], float)) < 0:
        out = out[:, ::-1]           # a mirroring map flips the winding: restore outward normals
    return out


def signed_volume(tris):
    return float(np.einsum("ij,ij->i", tris[:, 0], np.cross(tris[:, 1], tris[:, 2])).sum() / 6.0)


def _axis_winding(tris, axes, ax):
    """Winding number along +ax at every grid point (grid given by the three sorted coordinate arrays)."""
    a1, a2 = [i for i in range(3) if i != ax]
    u, v, w = axes[a1], axes[a2], axes[ax]
    nu, nv, nw = len(u), len(v), len(w)
    delta = np.zeros((nu, nv, nw + 1), np.int32)
    P = tris
    nrm = np.cross(P[:, 1] - P[:, 0], P[:, 2] - P[:, 0])
    for t in range(len(P)):
        nz = nrm[t, ax]
        if abs(nz) < 1e-12:
            continue
        p0, p1, p2 = P[t]
        umin, umax = min(p0[a1], p1[a1], p2[a1]), max(p0[a1], p1[a1], p2[a1])
        vmin, vmax = min(p0[a2], p1[a2], p2[a2]), max(p0[a2], p1[a2], p2[a2])
        iu0, iu1 = np.searchsorted(u, umin), np.searchsorted(u, umax, "right")
        iv0, iv1 = np.searchsorted(v, vmin), np.searchsorted(v, vmax, "right")
        if iu0 >= iu1 or iv0 >= iv1:
            continue
        U, V = np.meshgrid(u[iu0:iu1], v[iv0:iv1], indexing="ij")
        # barycentric in the (a1, a2) projection
        x0, y0 = p0[a1], p0[a2]
        x1, y1 = p1[a1] - x0, p1[a2] - y0
        x2, y2 = p2[a1] - x0, p2[a2] - y0
        den = x1 * y2 - x2 * y1
        if abs(den) < 1e-15:
            continue
        px, py = U - x0, V - y0
        l1 = (px * y2 - x2 * py) / den
        l2 = (x1 * py - px * y1) / den
        l0 = 1 - l1 - l2
        inside = (l0 >= 0) & (l1 >= 0) & (l2 >= 0)
        if not inside.any():
            continue
        W = p0[ax] + l1 * (p1[ax] - p0[ax]) + l2 * (p2[ax] - p0[ax])
        k = np.searchsorted(w, W[inside])          # samples at index >= k are beyond this crossing
        sgn = 1 if nz < 0 else -1                  # entering through a face whose normal points against the ray
        iu, iv = np.nonzero(inside)
        np.add.at(delta, (iu + iu0, iv + iv0, k), sgn)
    wind = np.cumsum(delta, axis=2)[:, :, :nw]
    order = [0, 0, 0]
    order[a1], order[a2], order[ax] = 0, 1, 2
    return np.transpose(wind, np.argsort([a1, a2, ax]))


def inside_grid(tris, xs, ys, zs):
    """Boolean inside mask on the grid xs x ys x zs (mesh coordinates).  Coordinates are jittered by a tiny
    irrational amount so rays never pass exactly through vertices or edges."""
    j = 1e-5 * np.array([0.7071, 0.5773, 0.4142])
    axes = [np.asarray(xs) + j[0], np.asarray(ys) + j[1], np.asarray(zs) + j[2]]
    if signed_volume(tris) < 0:
        tris = tris[:, ::-1]
    votes = np.zeros((len(xs), len(ys), len(zs)), np.int8)
    for ax in range(3):
        votes += (_axis_winding(tris, axes, ax) > 0).astype(np.int8)
    return votes >= 2


class MeshSolid:
    """A mesh as an implicit component on a lattice (evaluated once on the lattice's sample grid)."""
    kind = "mesh"

    def __init__(self, tris, cid="mesh"):
        self.tris = tris
        self.id = cid
        self.role = "fuselage"
        self.moves = False

    def bbox(self):
        p = self.tris.reshape(-1, 3)
        return p.min(0), p.max(0)

    def inside_on_axes(self, X, Y, Z):
        """X, Y, Z: grid-order sample axes (design y, z, x).  Returns mask indexed [X, Y, Z]."""
        m = inside_grid(self.tris, Z, X, Y)          # mesh in design coords: (x, y, z)
        return np.transpose(m, (1, 2, 0))
